// Development only: derive the offline Umm al-Qura month table from ICU, so the TV needs no calendar data.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const FIRST = 1440, LAST = 1500, DAY = 86400000;
const format = new Intl.DateTimeFormat('en-u-ca-islamic-umalqura', { timeZone: 'UTC', year: 'numeric', month: 'numeric', day: 'numeric' });
const hijri = day => Object.fromEntries(format.formatToParts(new Date(day * DAY)).filter(p => ['year', 'month', 'day'].includes(p.type)).map(p => [p.type, Number(p.value)]));

const starts = [], months = (LAST - FIRST + 1) * 12;
for (let day = Date.UTC(2017, 0, 1) / DAY; starts.length <= months; day++) {
  if (day > Date.UTC(2080, 0, 1) / DAY) throw Error('ICU did not reach ' + (LAST + 1) + ' AH');
  const h = hijri(day);
  if (h.day === 1 && (starts.length || h.year === FIRST && h.month === 1)) starts.push(day);
}
const lengths = starts.slice(1).map((day, i) => day - starts[i]);
if (lengths.some(n => n !== 29 && n !== 30)) throw Error('Unexpected Umm al-Qura month length');
const data = { firstYear: FIRST, epochDay: starts[0], months: lengths.map(n => n === 30 ? '1' : '0').join('') };
writeFileSync(root + 'app/assets/hijri.js', '/* Generated by scripts/build-hijri.mjs from ICU ' + process.versions.icu + ' islamic-umalqura, ' + FIRST + '-' + LAST + ' AH.\n   Month lengths from 1 Muharram ' + FIRST + ' (epochDay, days since 1970-01-01): 1 = 30 days, 0 = 29 days. */\nwindow.CleanFrameHijri = ' + JSON.stringify(data) + ';\n');
console.log('Umm al-Qura ' + FIRST + '-' + LAST + ' AH: ' + lengths.length + ' months from day ' + starts[0] + '.');
